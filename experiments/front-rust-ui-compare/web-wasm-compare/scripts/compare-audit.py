#!/usr/bin/env python3
import json, pathlib, sys
p=pathlib.Path(sys.argv[1])
sections=json.loads((p/'size-audit.json').read_text())
browser=json.loads((p/'browser.json').read_text())
expected=['rust-small','rust-fast','rust-nostd-small','rust-nostd-fast','zig-small','zig-fast']
assert sorted(browser['summary'])==sorted(expected),(list(browser['summary']),expected)
assert len(browser['byte_parity'])==3
for v in expected:
 rows=[r for r in browser['runs'] if r['variant']==v]
 assert len(rows)==3,(v,len(rows))
 assert all(r['suite']['parity']==browser['byte_parity'] for r in rows)
 assert v in sections
lines=['# WASM code root-cause audit: Rust std vs no_std vs Zig','',
       'All variants generated byte-identical HTML for 3/300/10000 objects in real Chromium.','',
       '| Variant | Raw WASM B | Executable code B | Custom sections B | Functions | Bundle Brotli B |',
       '|---|---:|---:|---:|---:|---:|']
for v in expected:
 a=sections[v];bundle=browser['package_sizes'][v]['total']['brotli']
 lines.append(f"| {v} | {a['raw']} | {a['code']} | {a['custom']} | {a['functions']} | {bundle} |")
lines+=['','Same Rust renderer code in std and no_std; no_std changes panic handling.',
        'Zig source is a separate implementation with identical output and ABI.',
        'The four baseline packages are not fully featured frontend frameworks.',
        'Custom sections do not contain WASM instructions.',
        'The browser tested dynamic DOM and button handling; synthetic events are not human input.']
summary='\n'.join(lines)+'\n'
(p/'size-audit-summary.md').write_text(summary)
print(summary)
